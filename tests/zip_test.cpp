template <typename F>
bool throws(F&& f) {
    try {
        f();
    } catch (const std::exception&) {
        return true;
    }
    return false;
}

std::vector<std::uint8_t> bytes(const std::string& s) { return {s.begin(), s.end()}; }

// 400 pseudo-random words; compressed below with dynamic Huffman codes.
std::string dynamicText() {
    static const char* words[] = {"tank", "infantry", "hovercraft", "mine", "road", "wall", "ruin", "colony", "province", "turn"};
    std::string s;
    std::uint32_t x = 1;
    for (int i = 0; i < 400; ++i) {
        x = (x * 1103515245u + 12345u) & 0x7FFFFFFFu;
        s += words[x % 10];
        s += x % 7 ? ' ' : '\n';
    }
    return s;
}

