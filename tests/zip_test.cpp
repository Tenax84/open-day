// "OpenDay OpenDay OpenDay, fixed Huffman codes: " + 'a' x N + "!" (286
// bytes), compressed with the fixed codes (long matches, distance 1).
const std::vector<std::uint8_t> kFixed = {
    0xf3, 0x2f, 0x48, 0xcd, 0x73, 0x49, 0xac, 0x54, 0xf0, 0x47, 0xa5, 0x75, 0x14, 0xd2, 0x32, 0x2b,
    0x52, 0x53, 0x14, 0x3c, 0x4a, 0xd3, 0xd2, 0x72, 0x13, 0xf3, 0x14, 0x92, 0xf3, 0x53, 0x52, 0x8b,
    0xad, 0x14, 0x12, 0x47, 0x16, 0x50, 0x04, 0x00,
};

std::string fixedText() {
    std::string s = "OpenDay OpenDay OpenDay, fixed Huffman codes: ";
    s += std::string(286 - s.size() - 1, 'a');
    return s + "!";
}

void testCrc() {
    CHECK(crc32(bytes("123456789")) == 0xCBF43926u);
    CHECK(crc32({}) == 0);
    // Running value: the CRC of the parts equals that of the whole.
    CHECK(crc32(bytes("6789"), crc32(bytes("12345"))) == 0xCBF43926u);
}

void testInflate() {
    const std::vector<std::uint8_t> dyn = inflate(kDynamic);
    CHECK(dyn == bytes(dynamicText()));
    CHECK(crc32(dyn) == 0xEAF17F3Au);
    CHECK((kDynamic[0] >> 1 & 3) == 2);

    CHECK((kFixed[0] >> 1 & 3) == 1);
    CHECK(inflate(kFixed) == bytes(fixedText()));

    // A stored block followed by a final fixed block with only end-of-block:
    // the stored block starts at a byte boundary.
    std::vector<std::uint8_t> stored = {0x00, 5, 0, 0xFA, 0xFF, 'h', 'e', 'l', 'l', 'o', 0x03, 0x00};
    CHECK(inflate(stored) == bytes("hello"));

    std::vector<std::uint8_t> truncated(kDynamic.begin(), kDynamic.begin() + 100);
    CHECK(throws([&] { inflate(truncated); }));
    CHECK(throws([] { inflate(std::vector<std::uint8_t>{0x07}); }));                         // block type 3
    CHECK(throws([] { inflate(std::vector<std::uint8_t>{0x01, 5, 0, 0, 0, 'h'}); }));        // bad stored length
    CHECK(throws([] { inflate(std::vector<std::uint8_t>{}); }));
}

// The compressor, checked by inflating its output: empty input, text, long
// runs (matches of 258 bytes, overlapping copies), and noise mixed with
// repeats at varied distances, longer than the 32 KiB window.
void testDeflate() {
    auto roundTrip = [](const std::vector<std::uint8_t>& data) { return inflate(deflate(data)) == data; };
    CHECK(roundTrip({}));
    CHECK(roundTrip(bytes(dynamicText())));
    CHECK(roundTrip(std::vector<std::uint8_t>(100000, 7)));
    CHECK(deflate(std::vector<std::uint8_t>(100000, 7)).size() < 2000);
    std::vector<std::uint8_t> mixed;
    std::uint32_t seed = 12345;
    while (mixed.size() < 200000) {
        seed = seed * 1103515245u + 12345u;
        if (mixed.size() > 1000 && (seed >> 16) % 4 == 0) {
            const std::size_t distance = 1 + (seed >> 8) % std::min<std::size_t>(mixed.size(), 40000);
            const std::size_t length = (seed >> 4) % 300;
            for (std::size_t k = 0; k < length; ++k) mixed.push_back(mixed[mixed.size() - distance]);
        } else {
            mixed.push_back(static_cast<std::uint8_t>(seed >> 24));
        }
    }
    CHECK(roundTrip(mixed));
}

void testZip() {
    const std::vector<std::uint8_t> zip = writeZip({
        {"readme.txt", bytes("stored member"), {}},
        {"maps/", {}, {}},
        {"maps/s1-1-1.mdb", bytes(dynamicText()), kDynamic},
    });
    const ZipArchive z = ZipArchive::fromBytes(zip);
    CHECK(z.entries().size() == 3);
    if (z.entries().size() == 3) {
        CHECK(z.entries()[0].name == "readme.txt");
        CHECK(z.entries()[0].method == 0);
        CHECK(z.read(z.entries()[0]) == bytes("stored member"));
        CHECK(z.entries()[1].isDirectory());
        CHECK(z.entries()[2].method == 8);
        CHECK(z.entries()[2].size == dynamicText().size());
        CHECK(z.read(z.entries()[2]) == bytes(dynamicText()));
        ZipEntry wrongCrc = z.entries()[0];
        wrongCrc.crc ^= 1;
        CHECK(throws([&] { z.read(wrongCrc); }));
    }

    // An archive comment after the end record.
    std::vector<std::uint8_t> commented = zip;
    commented[commented.size() - 2] = 4;
    for (char c : std::string("note")) commented.push_back(static_cast<std::uint8_t>(c));
    CHECK(ZipArchive::fromBytes(commented).entries().size() == 3);

    CHECK(throws([] { ZipArchive::fromBytes(bytes("not a zip archive at all, sorry")); }));
}

void testGamePath() {
    const fs::path root = fs::temp_directory_path() / "openday_zip_test_game";
    fs::remove_all(root);
    fs::create_directories(root / "interf");
    std::ofstream(root / "interf" / "pal.bmp") << "x";
    const fs::path found = findGameFile(root, "INTERF/PAL.BMP");
    CHECK(fs::exists(found));
    CHECK(sameNameIgnoreCase(found.filename().string(), "PAL.BMP"));
    CHECK(findGameFile(root, "INTERF/NONE.BMP") == root / "INTERF/NONE.BMP");
    CHECK(sameNameIgnoreCase("Scen1.Zip", "SCEN1.ZIP"));
    CHECK(!sameNameIgnoreCase("SCEN1.ZIP", "SCEN2.ZIP"));
    fs::remove_all(root);
}

